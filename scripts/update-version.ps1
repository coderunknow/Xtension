<#
.SYNOPSIS
  Generates every version-bearing artifact from the single source of truth, the VERSION file.
.DESCRIPTION
  Writes build/generated/VersionInfo.g.cs (ProductVersion + assembly version attributes) and
  build/generated/app.manifest (from app.manifest.template). Runs before every build: from the csproj
  PreBuildEvent and from scripts/build.ps1. Fails on a missing or malformed VERSION, so an unversioned
  binary cannot be produced. Files are rewritten only when their content changes.
#>
[CmdletBinding()]
param(
    [string]$RepoRoot = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

function Write-IfChanged([string]$Path, [string]$Content) {
    $normalized = $Content.Replace("`r`n", "`n").TrimEnd() + "`n"
    $current = if (Test-Path -LiteralPath $Path) { [System.IO.File]::ReadAllText($Path, $utf8NoBom).Replace("`r`n", "`n") } else { '' }
    if ($current -ne $normalized) {
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Path) | Out-Null
        [System.IO.File]::WriteAllText($Path, $normalized, $utf8NoBom)
        return $true
    }
    return $false
}

$versionFile = Join-Path $RepoRoot 'VERSION'
if (-not (Test-Path -LiteralPath $versionFile)) { throw "VERSION file not found: $versionFile" }
$version = ([System.IO.File]::ReadAllText($versionFile, $utf8NoBom)).Trim()
# SemVer 2.0 core with an optional pre-release tag such as 0.1.0-dev1.
$pattern = '^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(-[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?$'
if ($version -notmatch $pattern) { throw "VERSION '$version' is not a valid SemVer string." }

# Windows assembly versions must be four numeric parts, so the pre-release tag is dropped here.
$assemblyVersion = $version.Split('-')[0] + '.0'

$versionSource = @"
// <auto-generated>
// Generated by scripts/update-version.ps1 from the VERSION file. Do not edit.
// </auto-generated>
using System.Reflection;

[assembly: AssemblyVersion("$assemblyVersion")]
[assembly: AssemblyFileVersion("$assemblyVersion")]
[assembly: AssemblyInformationalVersion("$version")]

namespace Xtension
{
    internal static class ProductVersion
    {
        public const string Semantic = "$version";
        public const string Display = "v$version";
        public const string AssemblyVersion = "$assemblyVersion";
    }
}
"@

$templatePath = Join-Path $RepoRoot 'app.manifest.template'
if (-not (Test-Path -LiteralPath $templatePath)) { throw "Manifest template not found: $templatePath" }
$manifest = [System.IO.File]::ReadAllText($templatePath, $utf8NoBom).Replace('@ASSEMBLY_VERSION@', $assemblyVersion)

$generatedDir = Join-Path $RepoRoot 'build\generated'
$changedA = Write-IfChanged (Join-Path $generatedDir 'VersionInfo.g.cs') $versionSource
$changedB = Write-IfChanged (Join-Path $generatedDir 'app.manifest') $manifest
if ($changedA -or $changedB) {
    Write-Host "Generated version artifacts for $version (assembly $assemblyVersion)."
} else {
    Write-Host "Version artifacts are up to date ($version)."
}
