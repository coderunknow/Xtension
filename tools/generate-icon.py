#!/usr/bin/env python3
"""Generates the Xtension application icon from source, with no third-party dependency.

The icon is a rounded blue tile with a white multiplication sign: the product mark for "one close button on the
selected tab". It is rendered here with plain arithmetic (no SVG renderer, no Pillow, no ImageMagick) so the asset can
be regenerated byte-for-byte on any machine that has Python 3.8 or newer, which keeps the committed .ico reviewable
and reproducible instead of being an opaque binary nobody can rebuild.

Frames written into assets/xtension.ico are classic 32-bit BMP/DIB frames (with the AND mask Windows still expects)
at every size Explorer, the notification area and the file properties dialog ask for: 16, 20, 24, 32, 40, 48, 64,
128 and 256 pixels. A 256 pixel PNG copy is written next to it for documentation and review.

Usage:
    python3 tools/generate-icon.py [--check]

    --check   Re-generate in memory and compare with the committed file; exit non-zero on any difference.
              The packaging check and the CI static job use this so a hand-edited icon cannot slip in.

The renderer supersamples every frame four times and averages the samples, which is what keeps the diagonal strokes
and the rounded corners clean at 16 pixels. Small frames also use a heavier stroke and a shorter shadow, because a
proportionally scaled 256 pixel design turns into a grey smudge at 16 pixels.
"""
import os
import struct
import sys
import zlib
import pathlib

SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)
SUPERSAMPLE = 4
ICO_NAME = 'xtension.ico'
PREVIEW_NAME = 'xtension-256.png'

# Palette: a calm blue tile with a darker lower half, so the white cross keeps contrast on both light and dark
# desktops, and a slight top sheen that reads as depth at 32 pixels and above.
TOP = (56, 122, 246)
BOTTOM = (23, 58, 153)
BORDER = (168, 197, 255)
SHEEN = (255, 255, 255)


def lerp(a, b, t):
    return a + (b - a) * t


def mix(color_a, color_b, t, alpha_a=1.0, alpha_b=1.0):
    """Linear blend of two straight-alpha RGBA samples."""
    out_a = lerp(alpha_a, alpha_b, t)
    if out_a <= 0:
        return (0, 0, 0, 0)
    r = lerp(color_a[0] * alpha_a, color_b[0] * alpha_b, t) / out_a
    g = lerp(color_a[1] * alpha_a, color_b[1] * alpha_b, t) / out_a
    b = lerp(color_a[2] * alpha_a, color_b[2] * alpha_b, t) / out_a
    return (r, g, b, out_a)


def over(dst, src):
    """Source-over compositing for straight-alpha RGBA samples."""
    sr, sg, sb, sa = src
    if sa <= 0:
        return dst
    dr, dg, db, da = dst
    out_a = sa + da * (1 - sa)
    if out_a <= 0:
        return (0, 0, 0, 0)
    r = (sr * sa + dr * da * (1 - sa)) / out_a
    g = (sg * sa + dg * da * (1 - sa)) / out_a
    b = (sb * sa + db * da * (1 - sa)) / out_a
    return (r, g, b, out_a)


def rounded_rect_sdf(x, y, half_w, half_h, radius):
    """Signed distance from a rounded rectangle centred on the origin: negative inside."""
    dx = abs(x) - (half_w - radius)
    dy = abs(y) - (half_h - radius)
    ax = max(dx, 0.0)
    ay = max(dy, 0.0)
    outside = (ax * ax + ay * ay) ** 0.5
    inside = min(max(dx, dy), 0.0)
    return outside + inside - radius


def segment_distance(px, py, ax, ay, bx, by):
    vx = bx - ax
    vy = by - ay
    wx = px - ax
    wy = py - ay
    length_sq = vx * vx + vy * vy
    t = 0.0 if length_sq <= 0 else max(0.0, min(1.0, (wx * vx + wy * vy) / length_sq))
    cx = ax + vx * t
    cy = ay + vy * t
    return ((px - cx) ** 2 + (py - cy) ** 2) ** 0.5


def render(size):
    """Returns straight-alpha RGBA pixels for one frame, row by row from the top."""
    n = size * SUPERSAMPLE
    centre = n / 2.0
    half = n / 2.0
    # Insets keep a little breathing room so the tile does not touch the frame edge at small sizes.
    margin = n * (0.02 if size >= 32 else 0.0)
    half_w = half - margin
    half_h = half - margin
    radius = n * 0.235
    border_width = max(1.0, n * 0.012)
    # Stroke width and shadow grow with the frame; the small sizes get a relatively heavier cross.
    stroke = n * (0.105 if size >= 32 else 0.125)
    shadow_offset = n * (0.022 if size >= 32 else 0.012)

    arm = n * 0.225
    rows = []
    for y in range(n):
        row = []
        for x in range(n):
            px = x + 0.5 - centre
            py = y + 0.5 - centre
            distance = rounded_rect_sdf(px, py, half_w, half_h, radius)
            if distance > 0:
                row.append((0.0, 0.0, 0.0, 0.0))
                continue

            t = (y + 0.5) / n
            color = mix(TOP, BOTTOM, t, 1.0, 1.0)
            # Top sheen: strongest at the top, gone by 45% of the height.
            sheen = max(0.0, 1.0 - t / 0.45) * 0.13
            color = over(color, (SHEEN[0], SHEEN[1], SHEEN[2], sheen))
            # Inner hairline border.
            if distance > -border_width:
                edge = min(1.0, (-distance) / border_width)
                color = over(color, (BORDER[0], BORDER[1], BORDER[2], 0.55 * edge))

            # Cross shadow first, then the cross itself, both with round caps.
            if segment_distance(x + 0.5, y + 0.5, centre - arm, centre - arm + shadow_offset,
                                centre + arm, centre + arm + shadow_offset) <= stroke / 2 or \
               segment_distance(x + 0.5, y + 0.5, centre + arm, centre - arm + shadow_offset,
                                centre - arm, centre + arm + shadow_offset) <= stroke / 2:
                color = over(color, (8, 18, 48, 0.30))
            if segment_distance(x + 0.5, y + 0.5, centre - arm, centre - arm, centre + arm, centre + arm) <= stroke / 2 or \
               segment_distance(x + 0.5, y + 0.5, centre + arm, centre - arm, centre - arm, centre + arm) <= stroke / 2:
                color = over(color, (255, 255, 255, 1.0))
            row.append(color)
        rows.append(row)

    # Box downsampling of the supersampled buffer, averaged in premultiplied space so edges do not darken.
    out = []
    for y in range(size):
        row = []
        for x in range(size):
            r = g = b = a = 0.0
            for sy in range(SUPERSAMPLE):
                for sx in range(SUPERSAMPLE):
                    sr, sg, sb, sa = rows[y * SUPERSAMPLE + sy][x * SUPERSAMPLE + sx]
                    r += sr * sa
                    g += sg * sa
                    b += sb * sa
                    a += sa
            samples = SUPERSAMPLE * SUPERSAMPLE
            a /= samples
            if a <= 0:
                row.append((0, 0, 0, 0))
            else:
                row.append((int(round(r / samples / a)), int(round(g / samples / a)), int(round(b / samples / a)),
                            int(round(a * 255))))
        out.append(row)
    return out


def bmp_frame(pixels):
    """One ICO frame as a BITMAPINFOHEADER, 32-bit BGRA rows bottom-up, plus the legacy AND mask."""
    height = len(pixels)
    width = len(pixels[0])
    header = struct.pack('<IiiHHIIiiII', 40, width, height * 2, 1, 32, 0, 0, 0, 0, 0, 0)
    body = bytearray()
    for y in range(height - 1, -1, -1):
        for x in range(width):
            r, g, b, a = pixels[y][x]
            body += bytes((b, g, r, a))
    mask_stride = ((width + 31) // 32) * 4
    body += bytes(mask_stride * height)
    return header + bytes(body)


def png_image(pixels):
    height = len(pixels)
    width = len(pixels[0])
    raw = bytearray()
    for y in range(height):
        raw.append(0)
        for x in range(width):
            raw += bytes(pixels[y][x])

    def chunk(kind, data):
        return (struct.pack('>I', len(data)) + kind + data
                + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff))

    return (b'\x89PNG\r\n\x1a\n'
            + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(bytes(raw), 9))
            + chunk(b'IEND', b''))


def build_ico(frames):
    count = len(frames)
    header = struct.pack('<HHH', 0, 1, count)
    directory = bytearray()
    data = bytearray()
    offset = 6 + 16 * count
    for size in SIZES:
        payload = frames[size]
        directory += struct.pack('<BBBBHHII', 0 if size >= 256 else size, 0 if size >= 256 else size, 0, 0, 1, 32,
                                 len(payload), offset)
        data += payload
        offset += len(payload)
    return bytes(header + directory + data)


def build():
    frames = {}
    rendered = {}
    for size in SIZES:
        pixels = render(size)
        rendered[size] = pixels
        frames[size] = bmp_frame(pixels)
    return build_ico(frames), png_image(rendered[256])


def main(argv):
    root = pathlib.Path(__file__).resolve().parents[1]
    assets = root / 'assets'
    ico_path = assets / ICO_NAME
    png_path = assets / PREVIEW_NAME
    ico_bytes, png_bytes = build()
    if '--check' in argv:
        ok = True
        for path, expected in ((ico_path, ico_bytes), (png_path, png_bytes)):
            if not path.exists():
                print('MISSING: ' + str(path.relative_to(root)))
                ok = False
                continue
            if path.read_bytes() != expected:
                print('STALE: ' + str(path.relative_to(root)) + ' does not match tools/generate-icon.py.')
                ok = False
        if ok:
            print('Icon check passed: %s and %s match the generator (%d sizes).'
                  % (ICO_NAME, PREVIEW_NAME, len(SIZES)))
            return 0
        return 1
    assets.mkdir(parents=True, exist_ok=True)
    ico_path.write_bytes(ico_bytes)
    png_path.write_bytes(png_bytes)
    print('Wrote %s (%d bytes, %d sizes) and %s (%d bytes).'
          % (ico_path.relative_to(root), len(ico_bytes), len(SIZES), png_path.relative_to(root), len(png_bytes)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
